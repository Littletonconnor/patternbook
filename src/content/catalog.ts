export const lessons: Lesson[] = topics.flatMap((topic) => topic.lessons);

export function lessonBySlug(slug: string) {
  return lessons.find((lesson) => lesson.slug === slug);
}

export function topicOf(lesson: Pick<Lesson, "slug">) {
  return topics.find((topic) => topic.lessons.some((l) => l.slug === lesson.slug));
}

export function neighbours(lesson: Pick<Lesson, "slug">) {
  const i = lessons.findIndex((l) => l.slug === lesson.slug);
  return {
    previous: i > 0 ? lessons[i - 1] : undefined,
    next: i >= 0 && i < lessons.length - 1 ? lessons[i + 1] : undefined,
  };
}

export function lessonsByLevel(level: Level) {
  return lessons.filter((lesson) => lesson.level === level);
}

export const starterLessons = lessons.filter((lesson) => lesson.starter);

export function totals(list: readonly Lesson[] = lessons) {
  const minutes = list.reduce((sum, lesson) => sum + lesson.minutes, 0);
  return { lessons: list.length, minutes };
}

export function formatMinutes(minutes: number) {
  if (minutes < 60) return `${minutes} min`;
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  return `${h}h ${String(m).padStart(2, "0")}m`;
}
